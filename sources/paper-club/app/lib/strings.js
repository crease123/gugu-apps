export function stringsFor(locale) {
  return /^zh/i.test(locale ?? '') ? STRINGS.zh : STRINGS.en
}

export function fmt(text, values = {}) {
  return text.replace(/\{(\w+)\}/g, (_, key) => (key === 's' ? (values.n === 1 ? '' : 's') : String(values[key] ?? '')))
}
